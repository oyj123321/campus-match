    chosen: List[str] = []

    # 兴趣映射：打乱 tag 顺序后各抽一句
    tag_order = list(dict.fromkeys(tags))
    rng.shuffle(tag_order)
    for tag in tag_order:
        lines = INTEREST_ICEBREAKERS.get(tag)
        if not lines:
            # 无映射：把 tag 自然嵌进一句口语
            lines = [
                f"听说你也喜欢{tag}，最近有没有相关想聊的，别整那些官话就行",
                f"问卷里我们都点了{tag}，你平时真的经常碰吗还是随手勾的哈哈",
            ]
        pick = rng.choice(lines)
        _dedupe_extend(chosen, [pick])
        if len(chosen) >= n:
            return chosen[:n]

    # 通用库补满
    general = list(GENERAL_CAMPUS_ICEBREAKERS)
    rng.shuffle(general)
    _dedupe_extend(chosen, general)
    return chosen[:n]


