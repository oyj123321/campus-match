def icebreaker_text(item: Union[str, dict]) -> str:
    if isinstance(item, dict):
        return str(item.get("tip") or item.get("send") or "")
    return str(item or "")


def is_stale_icebreaker_list(ice: Optional[Sequence]) -> bool:
    """空列表，或含旧人机模板特征 → 需要重算。"""
    if not ice:
        return True
    for item in ice:
        text = icebreaker_text(item)
        if any(m in text for m in OLD_ICEBREAKER_MARKERS):
            return True
    return False


def _stable_rng(seed: Optional[Union[int, str, Sequence[int]]] = None) -> random.Random:
    if seed is None:
        return random.Random(0)
    if isinstance(seed, int):
        return random.Random(seed)
    if isinstance(seed, (list, tuple)) and all(isinstance(x, int) for x in seed):
        a, b = (sorted(seed) + [0, 0])[:2]
        return random.Random((a * 1_000_003) ^ b)
    raw = str(seed).encode("utf-8")
    h = int(hashlib.md5(raw).hexdigest()[:16], 16)
    return random.Random(h)


def _dedupe_extend(pool: List[str], candidates: Iterable[str]) -> None:
    seen = set(pool)
    for c in candidates:
        c = (c or "").strip()
        if c and c not in seen:
            pool.append(c)
            seen.add(c)


