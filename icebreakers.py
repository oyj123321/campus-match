def icebreaker_text(item: Union[str, dict]) -> str:
    if isinstance(item, dict):
        return str(item.get("tip") or item.get("send") or "")
    return str(item or "")


def is_stale_icebreaker_list(ice: Optional[Sequence]) -> bool:
    if not ice:
        return True
    for item in ice:
        text = icebreaker_text(item)
        if any(m in text for m in OLD_ICEBREAKER_MARKERS):
            return True
    return False


def _stable_rng(seed: Optional[Union[int, str, Sequence[int]]] = None) -> random.Random:
    if seed is None:
        return random.Random(0)
    if isinstance(seed, int):
        return random.Random(seed)
    if isinstance(seed, (list, tuple)) and all(isinstance(x, int) for x in seed):
        a, b = (sorted(seed) + [0, 0])[:2]
        return random.Random((a * 1_000_003) ^ b)
    raw = str(seed).encode("utf-8")
    h = int(hashlib.md5(raw).hexdigest()[:16], 16)
    return random.Random(h)


def _dedupe_extend(pool: List[str], candidates: Iterable[str]) -> None:
    seen = set(pool)
    for c in candidates:
        c = (c or "").strip()
        if c and c not in seen:
            pool.append(c)
            seen.add(c)


def pick_icebreakers(
    shared_tags: Optional[Sequence[str]] = None,
    seed: Optional[Union[int, str, Sequence[int]]] = None,
    n: int = 3,
    my_school: Optional[str] = None,
    their_school: Optional[str] = None,
) -> List[str]:
    """
    按稳定 seed 抽取破冰口语。三池混合：
      1) 兴趣交集 (INTEREST_ICEBREAKERS)
      2) 本校专属 (SCHOOL_ICEBREAKERS[my_school])
      3) 跨校/通用 (CROSS_SCHOOL_ICEBREAKERS，如果双方不同校则优先)

    同校：兴趣1条 + 本校2条
    跨校：兴趣1条 + 跨校2条
    不足则互相补齐。
    """
    rng = _stable_rng(seed)
    tags = [t for t in (shared_tags or []) if t]
    chosen: List[str] = []

    # 1) 兴趣映射 — 1条
    tag_order = list(dict.fromkeys(tags))
    rng.shuffle(tag_order)
    for tag in tag_order:
        lines = INTEREST_ICEBREAKERS.get(tag)
        if not lines:
            lines = [
                f"听说你也喜欢{tag}，最近有没有相关想聊的，别整那些官话就行",
            ]
        _dedupe_extend(chosen, [rng.choice(lines)])
        break  # 只要1条兴趣

    # 2) 本校 / 跨校 — 2条
    same_school = my_school and their_school and my_school == their_school
    if same_school and my_school and my_school in SCHOOL_ICEBREAKERS:
        school_lines = list(SCHOOL_ICEBREAKERS[my_school])
    else:
        school_lines = list(CROSS_SCHOOL_ICEBREAKERS)

    rng.shuffle(school_lines)
    _dedupe_extend(chosen, school_lines[:3])

    # 不够 n 条 — 跨校库（同校也可用）+ 通用补满
    if len(chosen) < n:
        cross = list(CROSS_SCHOOL_ICEBREAKERS)
        rng.shuffle(cross)
        _dedupe_extend(chosen, cross[:n])
    return chosen[:n]


def library_stats() -> dict:
    tag_lines = sum(len(v) for v in INTEREST_ICEBREAKERS.values())
    school_totals = {s: len(v) for s, v in SCHOOL_ICEBREAKERS.items()}
    return {
        "version": "v3-macau-multi-school",
        "review": "2-agent adversarial (authenticity + usability)",
        "school_libraries": school_totals,
        "cross_school_lines": len(CROSS_SCHOOL_ICEBREAKERS),
        "interest_tags": len(INTEREST_ICEBREAKERS),
        "interest_lines": tag_lines,
        "total_lines": sum(school_totals.values()) + len(CROSS_SCHOOL_ICEBREAKERS) + tag_lines,
        "note": "school-aware: same-school gets campus-specific; cross-school gets cross-Macau topics",
    }
